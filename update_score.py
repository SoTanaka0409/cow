import codecs
import re

with codecs.open('Source/Score.cpp.utf8.txt', 'r', 'utf-8-sig') as f:
    text = f.read()

replacements = [
    (r'// スコア描画用デジタル数字画像アセットのロード（実在する正しいアセットパスを設定）', '// スコア描画用アセットロード'),
    (r'// 読み込み済みグラフィックハンドルの解放漏れを防止', '// グラフィックハンドルのメモリリーク防止'),
    (r'[ \t]*// 画面左上に「SCORE」テキストを描画\r?\n?', ''),
    (r'[ \t]*// 現在の合計スコアを数字画像で右側に描画\r?\n?', ''),
    (r'// 文字入力欄をアクティブ化し、キーボード入力を開始する', '// DxLibのキーボード入力システムを有効化'),
    (r'[ \t]*// 入力中の文字をplayerNameに取得し、画面にネームエントリー用の表示を描画\r?\n?', ''),
    (r'// 何か文字が入力されている状態でENTERが押されたら入力受付を終了', '// 入力完了判定（ENTERキー）'),
    (r'// 上位3位の中に今回のスコアが割り込める位置があるか探索', '// 上位3位以内にランクインしたか判定'),
    (r'// 下位の順位を1つずつ繰り下げる', '// 順位の繰り下げ'),
    (r'// 今回のプレイヤーとして仮登録（後にネーム入力値で確定）', '// 仮名"PLAYER"で登録。ネームエントリー後に確定する'),
    (r'// ファイルが存在しない場合は、NONE（スコア0）でダミーデータを作成して初期セーブを行う', '// ランキングファイルがない場合はダミーデータで新規作成'),
    (r'// 1コンボにつき基本点の20%のボーナス倍率を加算する', '// コンボボーナス: 1コンボあたり20%加算'),
    (r'// スコアが負の値に減少するのを防止', '// 負のスコアを防止'),
]

for old, new in replacements:
    text = re.sub(old, new, text)

text = re.sub(r'\n{3,}', '\n\n', text)

with codecs.open('Source/Score.cpp', 'w', 'utf-8-sig') as f:
    f.write(text)
