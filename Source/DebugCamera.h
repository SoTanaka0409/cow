#pragma once
#include "DxLib.h"

// リリースビルドへの意図せぬ混入を防ぐため、原則としてデバッグモード時のみインスタンス化すること
// ゲームの進行状態や当たり判定とは完全に独立して動かす、スペクテイター（自由移動）用カメラ
class DebugCamera
{
public:
	// デフォルトでは原点・無回転で生成されるため、プレイ中の視点から移行する場合は直後にInitialize()を呼ぶこと
	DebugCamera();
	~DebugCamera();

	// [入力] なし [出力] なし [副作用] なし
	// 視点切り替え時の急な座標ジャンプによる見失いを防ぐため、現在のアクティブカメラの姿勢をコピーして引き継ぐ
	void Initialize();

	// [入力] なし [出力] なし [副作用] DXライブラリのグローバルな3Dカメラ状態の上書き
	// 通常のゲームカメラの座標を上書き破壊してしまうため、デバッグカメラ有効時以外は絶対に呼び出さないこと
	void Update();

	// [入力] なし [出力] なし [副作用] OSのカーソル座標を画面中央へ強制移動
	// 画面端へのカーソル到達による旋回不能バグを防ぐため、毎フレーム中央に引き戻してマウスの移動差分（デルタ）を測る
	void UpdateRotate();

private:
	// メインカメラの座標を汚染しないよう、完全に切り離して保持されるデバッグ専用のワールド座標
	VECTOR position_;

	// ジンバルロック回避や計算の簡略化のため、クォータニオンではなくオイラー角（ラジアン）で保持する
	float horizontal_angle_;

	// 視点の上下反転（フリップバグ）を防ぐため、回転計算時に必ず±89度（π/2未満）でのクランプ処理を適用すること
	float vertical_angle_;
};