#pragma once

// ゲーム内のフィーバー状態（一定時間吸引強化・金牛の連続出現）を管理するクラス
class Fever
{
public:
	/*
	 * @brief フィーバー状態管理変数を初期化し安全な状態を作る
	 * [入力] なし
	 * [出力] なし
	 * [副作用] なし
	 */
	Fever();
	~Fever();

	/*
	 * @brief フィーバー中の画面演出および金牛の周期生成を行う
	 * [入力] なし
	 * [出力] なし
	 * [副作用] スクリーンの描画ブレンド設定変更、牛オブジェクトの生成、タイマー減算
	 */
	void Update();

	/*
	 * @brief フィーバーゲージを増加させる（将来用）
	 * [入力] value: 増加量
	 * [出力] なし
	 * [副作用] ゲージ値の変動
	 */
	void AddGauge(int value);

	/*
	 * @brief 現在フィーバー状態であるかを取得する
	 * [入力] なし
	 * [出力] フィーバー中ならtrue
	 * [副作用] なし
	 */
	bool IsFever();

	/*
	 * @brief プレイヤーの攻撃力を倍加しフィーバー状態へ移行する
	 * [入力] なし
	 * [出力] なし
	 * [副作用] プレイヤー攻撃ステータスの倍加、タイマー設定、フィーバーフラグON
	 */
	void StartFever(class Player3D* player);

	/*
	 * @brief プレイヤー能力を元に戻しステージ上に初期の獲物を補充する
	 * [入力] なし
	 * [出力] なし
	 * [副作用] プレイヤー攻撃ステータスの復元、各種アクターの新規生成、フィーバーフラグOFF
	 */
	void EndFever();

private:
	int dropTime;       // 難易度およびスコア調整のための金牛スポーン間隔
	int DropCount;      // スポーン周期を管理するためのフレームカウンター
	int gauge;         // UI表示やフィーバー発動判定に用いるゲージ蓄積値
	int timer;         // フィーバー終了判定に用いる残り継続フレーム数
	bool isFever;      // 他クラスから状態を参照・分岐させるためのフラグ
	float playerStatus;
	class Player3D* feverPlayer; // 終了時にステータスを復元するための対象プレイヤーポインタ
};

