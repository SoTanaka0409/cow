#pragma once

// ゲーム内のフィーバー（一定時間吸引強化・金牛の連続出現）状態を管理するクラス
class Fever
{
public:
	/*
	 * @brief フィーバー状態管理変数を初期値に設定する
	 * [入力] なし
	 * [出力] なし
	 * [副作用] なし
	 */
	Fever();
	~Fever();

	/*
	 * @brief フィーバー中の画面演出の描画と、時間経過による金の牛の周期生成を行う
	 * [入力] なし
	 * [出力] なし
	 * [副作用] スクリーンの描画ブレンド設定変更、牛オブジェクトの生成、タイマー減算
	 */
	void Update();

	/*
	 * @brief フィーバーゲージを増加させる（将来用）
	 * [入力] value: 増加量
	 * [出力] なし
	 * [副作用] ゲージ値の変動
	 */
	void AddGauge(int value);

	/*
	 * @brief 現在フィーバー状態であるかを取得する
	 * [入力] なし
	 * [出力] フィーバー中ならtrue
	 * [副作用] なし
	 */
	bool IsFever();

	/*
	 * @brief フィーバーを開始し、プレイヤーの吸引力を倍加してタイマーを設定する
	 * [入力] なし
	 * [出力] なし
	 * [副作用] プレイヤー攻撃ステータスの倍加、タイマー設定、フィーバーフラグON
	 */
	void StartFever();

	/*
	 * @brief フィーバーを終了し、プレイヤー能力を元に戻してステージ上に通常牛・金牛・羊を補充する
	 * [入力] なし
	 * [出力] なし
	 * [副作用] プレイヤー攻撃ステータスの復元、各種アクターの新規生成、フィーバーフラグOFF
	 */
	void EndFever();

private:
	int dropTime;       // 金の牛をスポーンさせる時間間隔の閾値
	int DropCount;      // 金の牛の次回スポーン用フレームカウンター
	int mGauge;         // フィーバーゲージ蓄積値
	int mTimer;         // フィーバー状態の残り継続フレーム数
	bool mIsFever;      // 現在フィーバー状態かどうかのフラグ
	float playerStatus; // フィーバー開始前のプレイヤー元攻撃ステータス退避用
};
