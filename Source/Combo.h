#pragma once

// 報酬スコアの倍率計算およびUI演出のトリガーを一元管理するクラス
// 外部からの不意な状態変更によるスコア計算バグを防ぐため、状態更新（加算・初期化）は内部に隠蔽する
class Combo
{
public:
	Combo();
	~Combo();

	// [入力] なし [出力] なし [副作用] 描画キューへのUI頂点データ追加
	// ゲームの進行停止時（ポーズ中など）にUI表示が欠損するのを防ぐため、Updateとは独立して実行される前提
	void Draw();

	// [入力] なし [出力] なし [副作用] 猶予タイマーの減算、0到達時のReset()呼び出し
	// 猶予時間の厳密な管理のため、FPS変動による判定ズレが起きないよう毎フレーム必ず実行すること
	void Update();

	// [入力] なし [出力] なし [副作用] カウント加算および猶予タイマーの最大値復帰
	// 複数部位ヒット時などの意図しない二重加算バグを防ぐため、攻撃判定側で1アクションにつき1回のみ呼ぶこと
	void AddHit();

	// [入力] なし [出力] なし [副作用] カウントとタイマーの0初期化、UI非表示状態への遷移
	// 前回のコンボ倍率が次回のプレイに適用されるバグを防ぐため、被弾時やシーン遷移時にも確実に呼ぶこと
	void Reset();

	// [入力] なし [出力] 現在のコンボ数 [副作用] なし
	int GetCombo() const;

	// [入力] なし [出力] スコア倍率（float） [副作用] なし
	// 業務ルール（企画仕様）に基づくスコア倍率の計算式をカプセル化して提供する
	float GetMultiplier() const;

private:
	// 倍率計算用のベース値。異常な加算によるオーバーフローや、UI表示枠のはみ出しに注意すること
	int combo_count_;

	// 毎フレーム減算される猶予時間。0.0fを下回った瞬間にコンボを強制終了(Reset)させるための基準値
	float combo_timer_;

	// 難易度設定やプレイヤーのスキル適用によって上限値が動的に変動する仕様のため、const定数化は避けている
	float combo_max_time_;

	// 毎フレームのテクスチャロードによるスパイク（処理落ち）を防ぐため、生成時に読み込んでハンドルを保持する
	int combo_image_;

	// コンボ終了時にも「フェードアウト演出」を表示し続ける仕様を満たすため、カウント数とは独立した描画フラグとして管理
	bool combo_show_;

	// UIアニメーションのイージング計算に渡す正規化時間用。演出の終了検知（状態遷移）にも使用する
	float combo_show_timer_;
};